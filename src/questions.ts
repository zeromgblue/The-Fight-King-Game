function rnd(n: number) { return Math.floor(Math.random() * n); }
function shuffle<T>(a: T[]): T[] {
  const r = a.slice();
  for (let i = r.length - 1; i > 0; i--) { const j = rnd(i + 1); [r[i], r[j]] = [r[j], r[i]]; }
  return r;
}

function build(subject: Subject, raw: Raw): Question {
  const [q, correct, wrongs, ex] = raw;
  const all = shuffle([correct, ...wrongs]);
  return { subject, q, choices: all, answer: all.indexOf(correct), ex: ex ?? `คำตอบที่ถูกคือ ${correct}` };
}

function numChoices(correct: number, spread: number, fmt: (n: number) => string = String): { choices: string[]; answer: number } {
  const set = new Set<number>([correct]);
  let guard = 0;
  while (set.size < 4 && guard++ < 50) {
    const d = (rnd(spread) + 1) * (Math.random() < 0.5 ? -1 : 1);
    set.add(correct + d);
  }
  const arr = shuffle([...set]);
  return { choices: arr.map(fmt), answer: arr.indexOf(correct) };
}

function mathQ(tier: number): Question {
  let q = '', correct = 0, spread = 6, ex = '';
  let fmt: (n: number) => string = String;
  const t = tier;
  const kind = rnd(t === 0 ? 3 : t === 1 ? 5 : 6);
  if (t === 0) {
    if (kind === 0) { const a = 5 + rnd(45), b = 5 + rnd(45); q = `${a} + ${b} = ?`; correct = a + b; }
    else if (kind === 1) { const a = 20 + rnd(60), b = 5 + rnd(a - 10); q = `${a} − ${b} = ?`; correct = a - b; }
    else { const a = 2 + rnd(10), b = 2 + rnd(10); q = `${a} × ${b} = ?`; correct = a * b; spread = 8; }
    ex = `คำตอบคือ ${correct}`;
  } else if (t === 1) {
    if (kind === 0) { const a = 3 + rnd(9), b = 10 + rnd(30); q = `ถ้า x + ${a} = ${a + b} แล้ว x เท่ากับเท่าใด`; correct = b; ex = `x = ${a + b} − ${a} = ${b}`; }
    else if (kind === 1) { const p = [10, 20, 25, 50][rnd(4)], n = (2 + rnd(9)) * 20; q = `${p}% ของ ${n} เท่ากับเท่าใด`; correct = (p * n) / 100; ex = `${n} × ${p}/100 = ${correct}`; }
    else if (kind === 2) { const a = 2 + rnd(9), b = 2 + rnd(9), c = 2 + rnd(9); q = `${a} × ${b} + ${c} = ?`; correct = a * b + c; ex = `${a * b} + ${c} = ${correct}`; spread = 8; }
    else if (kind === 3) { const a = 3 + rnd(12), b = 8 + rnd(15); q = `(−${a}) + ${b} = ?`; correct = b - a; ex = `${b} − ${a} = ${correct}`; }
    else { const w = 3 + rnd(10), h = 3 + rnd(10); q = `สี่เหลี่ยมผืนผ้ากว้าง ${w} ยาว ${h} หน่วย มีพื้นที่กี่ตารางหน่วย`; correct = w * h; ex = `${w} × ${h} = ${correct}`; spread = 8; }
  } else {
    if (kind === 0) { const x = 2 + rnd(10), a = 2 + rnd(4), b = 1 + rnd(9); q = `ถ้า ${a}x + ${b} = ${a * x + b} แล้ว x เท่ากับเท่าใด`; correct = x; ex = `${a}x = ${a * x}, x = ${x}`; spread = 4; }
    else if (kind === 1) { const r = 3 + rnd(13); q = `√${r * r} เท่ากับเท่าใด`; correct = r; ex = `${r} × ${r} = ${r * r}`; spread = 4; }
    else if (kind === 2) { const b = 2 + rnd(4), n = 2 + rnd(3); q = `${b}^${n} เท่ากับเท่าใด`; correct = Math.pow(b, n); ex = `${b} คูณกัน ${n} ตัว = ${correct}`; spread = 8; }
    else if (kind === 3) { const b = 2 + rnd(12), h = 2 * (2 + rnd(8)); q = `สามเหลี่ยมฐานยาว ${b} สูง ${h} หน่วย มีพื้นที่กี่ตารางหน่วย`; correct = (b * h) / 2; ex = `½ × ${b} × ${h} = ${correct}`; spread = 6; }
    else if (kind === 4) { const tri = [[3, 4, 5], [5, 12, 13], [6, 8, 10], [8, 15, 17]][rnd(4)]; q = `สามเหลี่ยมมุมฉากมีด้านประกอบมุมฉาก ${tri[0]} และ ${tri[1]} หน่วย ด้านตรงข้ามมุมฉากยาวเท่าใด`; correct = tri[2]; ex = `${tri[0]}² + ${tri[1]}² = ${tri[2]}²`; spread = 4; }
    else { const a = 2 + rnd(8), b = 2 + rnd(8); q = `(−${a}) × (−${b}) = ?`; correct = a * b; ex = `ลบคูณลบได้บวก = ${correct}`; spread = 8; }
  }
  const { choices, answer } = numChoices(correct, spread, fmt);
  return { subject: 'math', q, choices, answer, ex };
}

export function tierForLevel(level: number): number {
  return level <= 6 ? 0 : level <= 13 ? 1 : 2;
}

let lastQ = '';
export function randomQuestion(level: number, subject?: Subject): Question {
  const tier = tierForLevel(level);
  const subjects: Subject[] = ['history', 'math', 'science'];
  const s = subject ?? subjects[rnd(3)];
  for (let i = 0; i < 6; i++) {
    let qu: Question;
    if (s === 'math') qu = mathQ(tier);
    else {
      const bank = (s === 'history' ? HISTORY : SCIENCE)[tier];
      qu = build(s, bank[rnd(bank.length)]);
    }
    if (qu.q !== lastQ) { lastQ = qu.q; return qu; }
  }
  return mathQ(tier);
}
